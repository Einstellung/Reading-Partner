-- Account and device registration (docs/platform/665). Run once against the
-- Neon database before the first deploy; safe to run again.

CREATE TABLE IF NOT EXISTS users (
  sub        TEXT PRIMARY KEY,          -- Google account ID (id_token "sub")
  email      TEXT,
  name       TEXT,
  first_seen TIMESTAMPTZ NOT NULL,
  last_seen  TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS devices (
  id          TEXT PRIMARY KEY,         -- random per-install ID generated by the app
  user_sub    TEXT NOT NULL REFERENCES users (sub),
  platform    TEXT NOT NULL,
  os_version  TEXT,
  model       TEXT,
  app_version TEXT,
  first_seen  TIMESTAMPTZ NOT NULL,
  last_seen   TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS devices_user_sub ON devices (user_sub);
